from typing import List, Optional
from backend.models import ClientInquiryItem, ClientInquiryPackage, TransactionBase

def generate_client_inquiry(
    transactions: List[TransactionBase],
    client_name: str = "Client",
    period: str = "Current Reconciliation Period"
) -> ClientInquiryPackage:
    """Generate structured client inquiry package for ambiguous transactions."""
    items = []
    
    for tx in transactions:
        norm = tx.normalized_merchant or tx.original_description
        
        # Determine contextual question and multiple choice options
        if "AMAZON" in norm or "AMZN" in norm:
            question = "Could you clarify the business purpose of this Amazon purchase?"
            options = [
                "Job site materials & electrical hardware",
                "Office supplies / tech peripherals",
                "Personal expense (reimburse / owner draw)",
                "Tools under $2,500"
            ]
        elif "TARGET" in norm or "WALMART" in norm:
            question = "Is this purchase for shop/breakroom supplies, job tools, or personal items?"
            options = [
                "Shop & cleaning supplies",
                "Job site consumables",
                "Personal (Owner's Draw)"
            ]
        elif "PAYPAL" in norm or "VENMO" in norm or "ZELLE" in norm:
            question = "Who was the recipient and what goods/services were purchased via this electronic transfer?"
            options = [
                "1099 Subcontractor Labor (need W-9)",
                "Equipment / Material vendor payment",
                "Owner distribution / draw",
                "Reimbursement of business expense"
            ]
        elif "CAFE" in norm or "RESTAURANT" in norm or "COFFEE" in norm:
            question = "Was this dining transaction a business meal with a client/crew or personal?"
            options = [
                "Client development meeting (50% deductible)",
                "Overtime job-site crew meal (50% deductible)",
                "Personal meal (Owner's Draw - non-deductible)"
            ]
        elif tx.amount > 0:
            question = "Please confirm the customer or invoice number corresponding to this incoming deposit."
            options = [
                "Customer payment against open invoice",
                "Owner capital contribution",
                "Vendor rebate or refund",
                "Insurance reimbursement"
            ]
        else:
            question = tx.missing_information or f"What was the specific business purpose for payment to {norm}?"
            options = [
                "Electrical parts / job materials",
                "Subcontractor / professional service",
                "Vehicle fuel or maintenance",
                "Personal / Owner's Draw"
            ]
            
        items.append(ClientInquiryItem(
            transaction_id=tx.id,
            date=tx.date,
            amount=tx.amount,
            description=tx.original_description,
            normalized_merchant=norm,
            suggested_account=tx.suggested_account_id,
            question=question,
            options=options
        ))
        
    return ClientInquiryPackage(
        client_name=client_name,
        period=period,
        items=items,
        custom_message="Hello, during our monthly reconciliation we encountered a few transactions requiring clarification. Please review the items below and let us know the business purpose so we can accurately close your books."
    )

def format_inquiry_as_markdown(pkg: ClientInquiryPackage) -> str:
    """Format inquiry package into beautiful, ready-to-send Markdown."""
    lines = [
        f"# Transaction Clarification Request — {pkg.client_name}",
        f"**Reconciliation Period:** {pkg.period}",
        "",
        pkg.custom_message or "",
        "",
        "---",
        ""
    ]
    
    for idx, item in enumerate(pkg.items, start=1):
        sign = "+" if item.amount > 0 else "-"
        abs_amt = abs(item.amount)
        lines.append(f"### {idx}. {item.normalized_merchant} ({item.date}) — `{sign}${abs_amt:,.2f}`")
        lines.append(f"- **Original Bank Line:** `{item.description}`")
        lines.append(f"- **Question:** {item.question}")
        lines.append("- **Possible Categories:**")
        for opt in item.options:
            lines.append(f"  - [ ] {opt}")
        lines.append("- **Client Notes:** _________________________")
        lines.append("")
        
    lines.append("---")
    lines.append("*Generated by LedgerShield — Privacy-First Local Accounting Assistant*")
    return "\n".join(lines)
